import assert from 'node:assert/strict';
import { test } from 'node:test';
import { JSDOM } from 'jsdom';
import React from 'react';

test('manual flow: items, friends, shared allocation, result and persistent history', async () => {
  const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost:3000/' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, localStorage: dom.window.localStorage, React, IS_REACT_ACT_ENVIRONMENT: true });
  Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
  dom.window.scrollTo = () => {};
  dom.window.confirm = () => true;
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
  const { render, fireEvent, waitFor, cleanup, within } = await import('@testing-library/react');
  const { default: Bagiyuk } = await import('../src/components/bagiyuk');
  const { useBills } = await import('../src/lib/store');
  const app = render(React.createElement(Bagiyuk));
  fireEvent.click(app.getByRole('button', { name: /Tulis manual/ }));
  fireEvent.change(app.getByPlaceholderText('Makan bareng di mana?'), { target: { value: 'Makan siang QA' } });
  fireEvent.click(app.getByRole('button', { name: /Tambah item pesanan/ }));
  fireEvent.click(app.getByRole('button', { name: 'Tambah item' }));
  fireEvent.change(app.getByLabelText('Nama item'), { target: { value: 'Pizza sharing' } });
  fireEvent.change(app.getByLabelText('Harga satuan (Rp)'), { target: { value: '50001' } });
  fireEvent.click(within(app.getByRole('dialog')).getByRole('button', { name: 'Simpan item' }));
  await waitFor(() => assert.ok(app.queryByRole('button', { name: /Simpan 1 item/ })));
  fireEvent.click(app.getByRole('button', { name: /Simpan 1 item/ }));
  fireEvent.click(app.getByRole('button', { name: /Tambah teman/ }));
  fireEvent.change(app.getByLabelText('Tambah teman'), { target: { value: 'Nadia' } });
  fireEvent.click(app.getByRole('button', { name: 'Tambahkan teman' }));
  fireEvent.click(app.getByRole('button', { name: 'Simpan teman' }));
  fireEvent.click(app.getByRole('button', { name: 'Lanjut bagi tagihan' }));
  assert.ok((app.getByRole('button', { name: 'Lihat hasil patungan' }) as HTMLButtonElement).disabled);
  fireEvent.click(app.getByRole('button', { name: 'Kamu' }));
  fireEvent.click(app.getByRole('button', { name: 'Nadia' }));
  fireEvent.click(app.getByRole('button', { name: 'Lihat hasil patungan' }));
  await waitFor(() => assert.ok(app.getByText('Beres, tinggal transfer!')));
  assert.equal(useBills.getState().history.length, 1);
  const persisted = JSON.parse(localStorage.getItem('bagiyuk.v1')!);
  assert.equal(persisted.history[0].name, 'Makan siang QA');
  assert.equal(persisted.history[0].items[0].assigned.length, 2);
  fireEvent.click(app.getByRole('button', { name: 'Selesai, kembali ke beranda' }));
  fireEvent.click(app.getByRole('button', { name: 'Riwayat' }));
  fireEvent.click(app.getByRole('button', { name: /Makan siang QA/ }));
  await waitFor(() => assert.ok(app.getByText('Beres, tinggal transfer!')));
  assert.equal(useBills.getState().draft, null);
  cleanup(); dom.window.close();
});
